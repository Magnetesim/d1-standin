#!/usr/bin/env python3
"""Extract per-item art arrangements and dyes from the PS3 01.24 item definitions.

    python3 tools/item_art.py [CI ...] > private/item_art.tsv

Chain: content index -> 012f investment globals entry 4673 row {hash, 0, world_tag} -> definition
(package ps3_investment_globals_<(tag>>13 & 0x3fff) - 0x400>, entry tag & 0x1fff), identity-checked by
the item hash at definition +0x30. Inside a definition, arrays are laid out as
{u32 0x80800184, u32 count, u32 element tag, u32 0, u32 0, elements...}; two element tags matter:

  0x8080030a  {i8 class (-1 = any), u8, u16 art arrangement}  - Gjallarhorn (ci 2085) -> -1:1229, the
              value the PS4 sibling measured in-game for its Gjallarhorn, so this is the gear record.
  0x808018ea  {i8 channel, u8, u16 dye}  - channels 0/1/2 armour (and shaders), 5/6 weapons,
              10/11 ship, 14 sparrow, 15 ghost; read as the item's default dyes [U: no reader traced].

Output: ci, hash, arrangements "class:arr,...", dyes "channel:dye,..." ("-" when empty), talent grid
(the u16 after the definition's last 0x808017BD record; indexes 012f entry 4650, 1135 grids;
Gjallarhorn 2085 -> 303; -1 when absent).
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
import pkg_extract  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..")
ARRAY = 0x80800184
ARRANGEMENT, DYE = 0x8080030A, 0x808018EA
GRID_TAG = 0x808017BD


def content_rows():
    """Content index -> (item hash, world tag), from ps3_investment_globals_012f entry 4673 (an array
    {0x80800184, count, element tag, 0, 0} of 12-byte {u32 item hash, u32 0, u32 world tag} records)."""
    blob, _ = pkg_extract.extract_entry("ps3_investment_globals_012f", 4673)
    i = blob.find(struct.pack(">I", ARRAY))
    n = struct.unpack_from(">I", blob, i + 4)[0]
    return {k: (struct.unpack_from(">I", blob, i + 20 + 12 * k)[0], struct.unpack_from(">I", blob, i + 28 + 12 * k)[0])
            for k in range(n)}


def definition(tag):
    pkg = ((tag >> 13) & 0x3FFF) - 0x400
    blob, _ = pkg_extract.extract_entry(f"ps3_investment_globals_{pkg:04x}", tag & 0x1FFF)
    return blob


def arrays(blob, elem_tag):
    """All {i8 key, u8, u16 value} entries of arrays with this element tag, in definition order."""
    out = []
    marker = struct.pack(">I", ARRAY)
    i = blob.find(marker)
    while i >= 0:
        if i + 20 <= len(blob):
            n, t = struct.unpack_from(">II", blob, i + 4)
            if t == elem_tag and i + 20 + 4 * n <= len(blob):
                for k in range(n):
                    key, _, val = struct.unpack_from(">bBH", blob, i + 20 + 4 * k)
                    out.append((key, val))
        i = blob.find(marker, i + 1)
    return out


def talent_grid(blob):
    i = blob.rfind(struct.pack(">I", GRID_TAG))
    if i < 0 or i + 6 > len(blob):
        return -1
    return struct.unpack_from(">H", blob, i + 4)[0]


def main(argv):
    rows = content_rows()
    cis = [int(a) for a in argv] or sorted(rows)
    print("# GENERATED by tools/item_art.py: ci\thash\tarrangements(class:arr)\tdyes(channel:dye)\tgrid")
    for ci in cis:
        h, tag = rows[ci]
        try:
            blob = definition(tag)
        except Exception as exc:  # unresolvable world tag / missing block
            print(f"{ci}\t{h:#010x}\tERROR {exc}", file=sys.stderr)
            continue
        if struct.unpack_from(">I", blob, 0x30)[0] != h:
            print(f"{ci}\t{h:#010x}\tidentity mismatch", file=sys.stderr)
            continue
        fmt = lambda es: ",".join(f"{k}:{v}" for k, v in es) or "-"
        print(f"{ci}\t{h:#010x}\t{fmt(arrays(blob, ARRANGEMENT))}\t{fmt(arrays(blob, DYE))}\t{talent_grid(blob)}")


if __name__ == "__main__":
    main(sys.argv[1:])
